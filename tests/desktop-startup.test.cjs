const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { Branding } = require('../desktop/branding.cjs')
const { startupId, reportStartup } = require('../desktop/startup.cjs')

test('startup acknowledgments cannot escape their directory and are isolated per invocation', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'meal-startup-'))
  t.after(() => fs.rm(directory, { recursive: true, force: true }))
  const id = 'a'.repeat(32), other = 'b'.repeat(32)
  assert.equal(startupId(['app', `--meal-startup-id=${id}`]), id)
  assert.equal(startupId(['--meal-startup-id=../../bad']), null)
  reportStartup(directory, '../bad', 'ready')
  assert.deepEqual(await fs.readdir(directory), [])
  reportStartup(directory, id, 'ready')
  reportStartup(directory, other, 'error', 'Renderer launch failed')
  assert.deepEqual(JSON.parse(await fs.readFile(path.join(directory, `startup-${id}.json`))), { status: 'ready' })
  assert.equal(JSON.parse(await fs.readFile(path.join(directory, `startup-${other}.json`))).status, 'error')
})

test('business branding survives restart, preserves logo on rename, and rejects invalid names', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'meal-brand-'))
  t.after(() => fs.rm(directory, { recursive: true, force: true }))
  const brand = new Branding(directory)
  assert.deepEqual(await brand.load(), { name: 'Meal Planner', logo: null })
  const logo = Buffer.from('image bytes supplied by validated nativeImage')
  await brand.save('  Druhá Lab  ', logo)
  const restarted = new Branding(directory)
  assert.deepEqual(await restarted.load(), { name: 'Druhá Lab', logo: 'logo.png' })
  await restarted.save('New name')
  assert.deepEqual(await fs.readFile(path.join(brand.directory, 'logo.png')), logo)
  assert.match((await restarted.public()).logo, /^mealapp:\/\/local\/business-logo\/logo\.png\?v=/)
  await assert.rejects(restarted.save(' '))
  await assert.rejects(restarted.save('x'.repeat(81)))
  assert.equal((await restarted.load()).name, 'New name')
  await fs.writeFile(path.join(brand.directory, 'brand.json'), JSON.stringify({ name: 'Safe', logo: '../../secret.png' }))
  assert.equal((await brand.public()).logo, null)
})
